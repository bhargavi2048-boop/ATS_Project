TEAL = "#117A65"

# ---------------- FUNCTIONS ----------------

def extract_text(pdf_file):
    """Extracts text from a PDF file."""
    reader = PyPDF2.PdfReader(pdf_file)
    text = ""
    for page in reader.pages:
        text += page.extract_text()
    return text.lower()


def create_pdf_report(resumes_data):
    """Generates a professional PDF report for multiple resumes."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4)
    styles = getSampleStyleSheet()
    elements = []

    elements.append(Paragraph("<b>ATS Resume Evaluation Report</b>", styles["Title"]))
    elements.append(Spacer(1, 10))
    elements.append(Paragraph(f"Generated on: {datetime.datetime.now().strftime('%d %b %Y')}", styles["Normal"]))
    elements.append(Spacer(1, 10))

    for data in resumes_data:
        elements.append(Paragraph(f"<b>Candidate Resume:</b> {data['name']}", styles["Heading2"]))
        elements.append(Paragraph(f"Target Role: {data['role']}", styles["Normal"]))
        elements.append(Paragraph(f"Overall ATS Score: <b>{data['overall_score']}%</b>", styles["Normal"]))
        elements.append(Spacer(1, 5))

        # Score table
        table_data = [["Category", "Score (%)"]] + [[k, v] for k, v in data['scores'].items()]
        table = Table(table_data)
        table.setStyle(TableStyle([
            ("BACKGROUND", (0,0), (-1,0), colors.HexColor(TEAL)),
            ("TEXTCOLOR", (0,0), (-1,0), colors.white),
            ("GRID", (0,0), (-1,-1), 1, colors.black),
        ]))
        elements.append(table)
        elements.append(Spacer(1, 5))

        # Suggestions
        elements.append(Paragraph("<b>Improvement Recommendations:</b>", styles["Heading3"]))
        for tip in data['improvements']:
            elements.append(Paragraph(f"- {tip}", styles["Normal"]))

        # Strengths
        elements.append(Paragraph("<b>Resume Strengths:</b>", styles["Heading3"]))
        for s in data['strengths']:
            elements.append(Paragraph(f"- {s}", styles["Normal"]))

        elements.append(Spacer(1, 20))

    # Footer
    elements.append(Paragraph(
        "<i>Generated by Professional ATS Resume Scoring System</i>", styles["Normal"]
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer

